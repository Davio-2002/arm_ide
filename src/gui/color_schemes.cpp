std::span<const ColorScheme> colorSchemes() {
    return colorSchemeTable;
}

const ColorScheme *findColorScheme( std::string_view name ) {
    for ( const ColorScheme &candidate : colorSchemeTable ) {
        if ( name == candidate.name ) {
            return &candidate;
        }
    }
    return nullptr;
}
