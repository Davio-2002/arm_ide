const TextEditor::Language *cLanguage() {
    static TextEditor::Language language = [] {
        TextEditor::Language c = *TextEditor::LookupLanguageByExtension( ".c" );
        c.identifiers.insert( std::begin( libraryNames ), std::end( libraryNames ) );
        return c;
    }();
    return &language;
}
